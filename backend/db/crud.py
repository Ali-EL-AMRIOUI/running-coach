import logging
from sqlalchemy.orm import Session
from typing import Optional
from db import models

logger = logging.getLogger(__name__)


# USERS
# ------------------------------------------------------------

def get_user(db: Session, user_id: int) -> Optional[models.User]:
    return db.query(models.User).filter(models.User.id == user_id).first()


def get_user_by_email(db: Session, email: str) -> Optional[models.User]:
    return db.query(models.User).filter(models.User.email == email).first()


def create_user(db: Session, email: str, hashed_password: str) -> models.User:
    user = models.User(email=email, hashed_password=hashed_password)
    db.add(user)
    db.commit()
    db.refresh(user)
    logger.info(f"User created: {email}")
    return user


def update_user_profile(db: Session, user_id: int, data: dict) -> Optional[models.User]:
    user = get_user(db, user_id)
    if not user:
        return None
    for key, value in data.items():
        if hasattr(user, key):
            setattr(user, key, value)
    db.commit()
    db.refresh(user)
    return user


# TRAINING PLANS
# ------------------------------------------------------------

def save_plan(
    db: Session,
    user_id: int,
    plan_data: dict,
    distance: str,
    goal_date=None,
) -> models.TrainingPlan:
    """
    Saves the plan generated by agents to the database.
    Automatically extracts metadata from the plan.
    """
    # Extract metadata
    weeks_count     = len(plan_data.get("weeks", []))
    total_volume    = plan_data.get("total_km", 0.0)
    coach_analysis  = plan_data.get("coach_analysis", "")
    metadata        = plan_data.get("metadata", {})
    pace_zones      = metadata.get("zones", {})
    level           = metadata.get("level", None)
    is_valid        = metadata.get("is_valid", True)
    validation_errors = metadata.get("validation_errors", [])

    # Clean plan (remove internal metadata before saving)
    plan_to_save = {k: v for k, v in plan_data.items() if k != "metadata"}

    plan = models.TrainingPlan(
        user_id           = user_id,
        distance          = distance,
        goal_date         = goal_date,
        weeks_count       = weeks_count,
        plan              = plan_to_save,
        total_volume      = total_volume,
        coach_analysis    = coach_analysis,
        pace_zones        = pace_zones,
        level             = level,
        is_valid          = is_valid,
        validation_errors = validation_errors,
    )
    db.add(plan)
    db.commit()
    db.refresh(plan)
    logger.info(f"Plan saved - ID: {plan.id} | {weeks_count} weeks | {total_volume}km")
    return plan


def get_user_plans(
    db: Session,
    user_id: int,
    limit: int = 10,
) -> list[models.TrainingPlan]:
    return (
        db.query(models.TrainingPlan)
        .filter(models.TrainingPlan.user_id == user_id)
        .order_by(models.TrainingPlan.created_at.desc())
        .limit(limit)
        .all()
    )


def get_plan(db: Session, plan_id: int, user_id: int) -> Optional[models.TrainingPlan]:
    return (
        db.query(models.TrainingPlan)
        .filter(
            models.TrainingPlan.id == plan_id,
            models.TrainingPlan.user_id == user_id,
        )
        .first()
    )


def update_plan_feedback(
    db: Session,
    plan_id: int,
    user_id: int,
    rating: int,
    feedback: str,
) -> Optional[models.TrainingPlan]:
    plan = get_plan(db, plan_id, user_id)
    if not plan:
        return None
    plan.user_rating   = rating
    plan.user_feedback = feedback
    db.commit()
    db.refresh(plan)
    return plan


def delete_plan(db: Session, plan_id: int, user_id: int) -> bool:
    plan = get_plan(db, plan_id, user_id)
    if not plan:
        return False
    db.delete(plan)
    db.commit()
    return True


# WORKOUT LOGS
# ------------------------------------------------------------

def log_workout(
    db: Session,
    user_id: int,
    plan_id: Optional[int],
    data: dict,
) -> models.WorkoutLog:
    log = models.WorkoutLog(
        user_id          = user_id,
        plan_id          = plan_id,
        workout_type     = data.get("workout_type"),
        distance         = data.get("distance", 0),
        duration         = data.get("duration", 0),
        avg_pace         = data.get("avg_pace"),
        avg_hr           = data.get("avg_hr"),
        perceived_effort = data.get("perceived_effort"),
        notes            = data.get("notes"),
        completed        = data.get("completed", True),
        strava_activity_id = data.get("strava_activity_id"),
    )
    db.add(log)
    db.commit()
    db.refresh(log)
    return log


def get_user_logs(
    db: Session,
    user_id: int,
    limit: int = 20,
) -> list[models.WorkoutLog]:
    return (
        db.query(models.WorkoutLog)
        .filter(models.WorkoutLog.user_id == user_id)
        .order_by(models.WorkoutLog.date.desc())
        .limit(limit)
        .all()
    )