logger = logging.getLogger(__name__)

REST_SLOT = {"type": "REST", "km": 0, "pace": "N/A", "details": "Rest"}

GOAL_DIST_MAP = {
    "5k": 5.0, "10k": 10.0,
    "half": 21.0975, "marathon": 42.195,
}


class AgentOrchestrator:

    def __init__(self, db: Session, user_id: int):
        self.db        = db
        self.user_id   = user_id
        self.retriever = RetrieverAgent()
        self.analyzer  = AnalyzerAgent()
        self.planner   = PlannerAgent()
        self.validator = ValidatorAgent()
        self.explainer = ExplainerAgent()

    # UTILITIES
    # ------------------------------------------------------------

    def calculate_weeks(self, goal_date_str: str) -> int:
        try:
            goal_date = datetime.strptime(str(goal_date_str), "%Y-%m-%d")
            days      = (goal_date - datetime.now()).days
            return max(4, min(days // 7, 24))
        except Exception:
            return 12

    def goal_dist_km(self, request: PlanRequest) -> float:
        return GOAL_DIST_MAP.get(
            str(request.goal_distance).lower(), 21.0975
        )

    def build_athlete_context(self, request: PlanRequest, aerobic_profile: str = "unknown") -> str:
        """Short context for RAG (search query)."""
        records = []
        for dist, attr in [
            ("half", "record_half"), ("marathon", "record_marathon"),
            ("10k", "record_10000m"), ("5k", "record_5000m"),
            ("1500m", "record_1500m"), ("800m", "record_800m"),
            ("400m", "record_400m"),
        ]:
            val = getattr(request, attr, None)
            if val and str(val).strip() not in ("", "N/A"):
                records.append(f"{dist} {val}")
        records_str = ", ".join(records) if records else "records not specified"

        return (
            f"Athlete {request.age} years, {request.gender}, "
            f"profile {aerobic_profile}, "
            f"goal {request.goal_distance}, "
            f"current volume {request.current_volume}km/week, "
            f"frequency {request.current_frequency} sessions/week, "
            f"double session: {request.double_session}, "
            f"records: {records_str}"
        )

    def extract_directives(self, analysis_text: str) -> dict:
        """
        Robust extraction of LLM directives.
        Tries strict JSON, then partial JSON, then default values.
        """
        # Attempt 1: explicit PLANNER_DIRECTIVES block
        match = re.search(
            r"PLANNER_DIRECTIVES\s*:\s*(\{.*?\})",
            analysis_text, re.DOTALL
        )
        if match:
            try:
                return json.loads(match.group(1))
            except json.JSONDecodeError:
                pass

        # Attempt 2: first valid JSON block in text
        match = re.search(r"\{[^{}]*\}", analysis_text, re.DOTALL)
        if match:
            try:
                return json.loads(match.group(0))
            except json.JSONDecodeError:
                pass

        logger.warning("No JSON directives found - using default values")
        return {}

    # NORMALIZATION
    # ------------------------------------------------------------

    def normalize_plan_format(self, raw_plan: dict) -> dict:
        """
        Technical normalization only - JSON structure.
        Recalculates weekly_km from actual days (corrects LLM deviations).
        Does NOT modify paces generated by LLM.
        """
        if not isinstance(raw_plan, dict) or "weeks" not in raw_plan:
            return raw_plan

        total = 0.0
        n     = len(raw_plan["weeks"])

        for i, week in enumerate(raw_plan["weeks"]):
            # Default phase
            if "phase" not in week:
                if i < n * 0.4:
                    week["phase"] = "Base"
                elif i < n * 0.75:
                    week["phase"] = "Specific"
                elif i < n * 0.9:
                    week["phase"] = "Taper"
                else:
                    week["phase"] = "Race Week"

            # 7 complete days
            days = week.get("days", [])
            while len(days) < 7:
                days.append({
                    "day":       len(days) + 1,
                    "morning":   REST_SLOT.copy(),
                    "afternoon": REST_SLOT.copy(),
                })
            week["days"] = days

            for day in week["days"]:
                if "morning"   not in day: day["morning"]   = REST_SLOT.copy()
                if "afternoon" not in day: day["afternoon"] = REST_SLOT.copy()

            # ALWAYS recalculate weekly_km from actual days
            # Corrects discrepancies between declared weekly_km and actual km
            real_km = round(sum(
                (day.get("morning",   {}) or {}).get("km", 0)
                + (day.get("afternoon", {}) or {}).get("km", 0)
                for day in week["days"]
            ), 1)
            week["weekly_km"] = real_km

            total += real_km

        raw_plan["total_km"] = round(total, 1)
        return raw_plan

    # MAIN WORKFLOW
    # ------------------------------------------------------------

    def run_workflow(self, request: PlanRequest) -> Dict[str, Any]:
        logger.info(f"Workflow - user {self.user_id}")

        dist_km     = self.goal_dist_km(request)
        weeks_count = self.calculate_weeks(request.goal_date)
        logger.info(f"{weeks_count} weeks | goal {dist_km}km")

        # Step 1: Aerobic profile + objective references
        all_records  = extract_all_records(request)
        aerobic_prof = compute_aerobic_profile(all_records)
        aerobic_profile_str = aerobic_prof.get("profile", "unknown")

        references_block = build_athlete_references_prompt(request, dist_km)
        logger.info(f"Aerobic profile: {aerobic_profile_str}")

        # Race reference for metadata
        race_ref = best_race_reference(request, dist_km)
        ref_pace = race_ref["estimated_pace"] if race_ref else "N/A"

        # Step 2: Level + progression bounds
        level = detect_level(
            current_volume  = request.current_volume,
            record_half     = getattr(request, "record_half",     None),
            record_marathon = getattr(request, "record_marathon", None),
            record_10k      = getattr(request, "record_10000m",   None),
            years_practice  = getattr(request, "years_practice",  None),
        )
        progression_block = build_progression_prompt_block(
            current_volume = request.current_volume,
            goal_distance  = request.goal_distance,
            level          = level,
        )
        logger.info(f"Detected level: {level}")

        # Step 3: Contextual warnings (Safety Layer A)
        safety_warnings = build_athlete_context_warnings(request)
        for w in safety_warnings:
            logger.info(f"{w}")

        # Step 4: RAG
        athlete_context = self.build_athlete_context(request, aerobic_profile_str)
        try:
            knowledge_context = self.retriever.run(
                goal_distance    = request.goal_distance,
                goal_date        = str(request.goal_date),
                athlete_context  = athlete_context,
                aerobic_profile  = aerobic_profile_str,
                top_k            = 5,
            )
        except Exception as e:
            logger.error(f"RAG: {e}")
            knowledge_context = "No knowledge available."
        logger.info(f"RAG: {len(knowledge_context)} characters")

        # Step 5: Strategic analysis
        # Analyzer receives: RAG + references + progression + warnings
        analysis_context = self.analyzer.run(
            request,
            knowledge_context,
            extra_context={
                "references_block":  references_block,
                "safety_warnings":   safety_warnings,
                "progression_block": progression_block,
            }
        )
        logger.info(f"Analyzer:\n{analysis_context[-2000:]}")

        # Step 6: Directives for planner
        directives = self.extract_directives(analysis_context)

        directives["total_weeks"]            = weeks_count
        directives["reference_pace"]         = ref_pace
        directives["goal_distance_km"]       = dist_km
        directives["athlete_level"]          = level
        directives["aerobic_profile"]        = aerobic_profile_str
        directives["starting_volume_km"]     = request.current_volume
        directives["max_allowed_volume"]     = build_progression_prompt_block(
            request.current_volume, request.goal_distance, level
        )
        if safety_warnings:
            directives["athlete_context"]    = safety_warnings

        # Step 7: Plan generation (with regeneration on violation)
        normalized       = None
        hard_errors_last = []

        for attempt in range(3):
            raw_plan = None
            try:
                raw_plan = self.planner.run(
                    request          = request,
                    analysis_context = analysis_context,
                    weeks_count      = weeks_count,
                    directives       = directives,
                    previous_errors  = hard_errors_last if attempt > 0 else [],
                )
                logger.info(f"Plan generated (attempt {attempt + 1})")
            except Exception as e:
                logger.error(f"Planner attempt {attempt + 1}: {e}")
                continue

            # Normalization - recalculates weekly_km from actual km
            normalized = self.normalize_plan_format(raw_plan)

            # JSON structure validation
            is_valid, struct_errors = self.validator.run(
                normalized, request, zones={}
            )
            if not is_valid:
                logger.warning(f"Invalid structure: {struct_errors[:3]}")
                hard_errors_last = struct_errors
                directives["required_corrections"] = hard_errors_last
                continue

            # Physiological hard limits validation
            hard_check = validate_plan_hard_limits(
                plan_weeks   = normalized.get("weeks", []),
                request      = request,
                goal_dist_km = dist_km,
            )

            if hard_check["warnings"]:
                for w in hard_check["warnings"]:
                    logger.warning(f"Hard limit warning: {w}")

            if not hard_check["valid"]:
                hard_errors_last = hard_check["violations"]
                logger.error(
                    f"Hard limits violated (attempt {attempt + 1}): "
                    f"{hard_errors_last}"
                )
                directives["required_corrections"] = hard_errors_last
                continue

            logger.info(f"Hard limits OK (attempt {attempt + 1})")
            break

        else:
            logger.error("3 attempts exhausted - returning plan with violations")
            hard_check = {"valid": False, "violations": hard_errors_last, "warnings": []}

        # Step 8: Metadata
        normalized["metadata"] = {
            "user_id":            self.user_id,
            "weeks_count":        weeks_count,
            "goal_distance_km":   dist_km,
            "reference_pace":     ref_pace,
            "athlete_level":      level,
            "aerobic_profile":    aerobic_profile_str,
            "safety_warnings":    safety_warnings,
            "is_valid":           hard_check.get("valid", False),
            "hard_violations":    hard_check.get("violations", []),
            "hard_warnings":      hard_check.get("warnings",  []),
        }

        logger.info(
            f"Complete - {weeks_count} weeks, "
            f"{normalized.get('total_km', 0)}km, "
            f"valid={hard_check.get('valid')}"
        )
        return normalized