from pydantic import BaseModel, Field
from typing import List, Optional
from datetime import date, datetime

# ==========================================
# 1. USER REQUEST
# ==========================================
class PlanRequest(BaseModel):
    # REQUIRED FIELDS
    age: int
    gender: str = Field(..., pattern="^[MF]$")
    current_volume: float
    current_frequency: int
    goal_distance: str
    goal_date: date
    availability: int
    
    # OPTIONAL FIELDS
    record_400m: Optional[str] = None
    record_800m: Optional[str] = None
    record_1500m: Optional[str] = None
    record_5000m: Optional[str] = None
    record_10000m: Optional[str] = None
    record_half: Optional[str] = None
    record_marathon: Optional[str] = None
    
    age_start: Optional[int] = None
    years_practice: Optional[int] = None
    other_sports: Optional[str] = None
    
    volume_s4: Optional[float] = None
    volume_s3: Optional[float] = None
    volume_s2: Optional[float] = None
    volume_s1: Optional[float] = None
    last_week_training: Optional[str] = None
    
    double_session: str = "no"
    double_session_days: Optional[str] = None
    
    last_injury: Optional[str] = None
    return_date: Optional[date] = None


# ==========================================
# 2. BIDAILLY PROGRAM STRUCTURE (Generated by agents)
# ==========================================
class SessionDetails(BaseModel):
    type: str  # Run, Intervals, Strength, Threshold, Off, Rest
    km: float  # 0.0 if "Off" or "Strength"
    pace: str  # e.g., "3:55/km" or "N/A"
    details: str

class DailyTraining(BaseModel):
    day: int  # 1 to 7
    morning: SessionDetails
    afternoon: SessionDetails

class TrainingWeek(BaseModel):
    week: int
    phase: str  # Base, Preparation, Specific, Taper, Recovery
    weekly_km: float
    days: List[DailyTraining]

class TrainingPlanSchema(BaseModel):
    coach_analysis: str  
    total_km: float
    weeks: List[TrainingWeek]


# ==========================================
# 3. API HTTP RESPONSE
# ==========================================
class PlanResponse(BaseModel):
    id: int
    distance: str
    target_time: Optional[str] = None  # Format "hh:mm:ss" for frontend
    weeks: int
    plan: dict  # Will contain the serialized TrainingPlanSchema object as dict
    total_volume: float
    created_at: datetime 

    class Config:
        from_attributes = True